CREATE VIEW public.vw_progresso_modulo AS
 SELECT u.id AS aluno_id,
    m.id AS modulo_id,
    (count(a.id))::integer AS aulas_publicadas,
    (count(p.id) FILTER (WHERE ((p.status)::text = 'CONCLUIDA'::text)))::integer AS aulas_concluidas,
    (round(((100.0 * (count(p.id) FILTER (WHERE ((p.status)::text = 'CONCLUIDA'::text)))::numeric) / (count(a.id))::numeric)))::integer AS percentual
   FROM (((public.contas_usuario u
     CROSS JOIN public.trilha_modulo m)
     JOIN public.trilha_aula a ON (((a.modulo_id = m.id) AND a.publicada)))
     LEFT JOIN public.trilha_progressoaula p ON (((p.aula_id = a.id) AND (p.aluno_id = u.id))))
  WHERE (NOT u.is_staff)
  GROUP BY u.id, m.id;


